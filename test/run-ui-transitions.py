#!/usr/bin/env python3
"""Capture matched observational list/board, calendar, and sidebar heap profiles.

Build test-ui-transitions and test-schemas. Run in an isolated D-Bus/Xvfb session
with a fixture generated by create-memory-fixtures.py. Retention and calendar
bounds are observations; functional assertions remain fatal. Existing strict UI
memory tests are unchanged.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import signal
import sqlite3
import subprocess
import time


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fixture', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--binary', required=True, type=Path)
    parser.add_argument('--schemas', required=True, type=Path)
    parser.add_argument('--revision', required=True, help='Production commit recorded in the manifest')
    parser.add_argument('--timeout', type=int, default=1800)
    args = parser.parse_args()
    fixture = args.fixture.resolve()
    root = args.output.resolve()
    binary = args.binary.resolve()
    schemas = args.schemas.resolve()
    manifest = json.loads((fixture / 'manifest.json').read_text())
    assert manifest['network_accounts'] is False
    assert manifest['counts']['items'] in (450, 5000)
    database = Path('data/io.github.alainm23.planify/database.db')
    assert digest(fixture / database) == manifest['sha256']
    if root.exists():
        parser.error('Output exists; choose a new directory to preserve recordings.')
    if not (schemas / 'gschemas.compiled').is_file():
        parser.error('Build test-schemas or provide a compiled settings-schema directory.')
    harness = binary.parents[2] / 'test/ui-transition-profile.vala'
    shutil.copytree(fixture, root)
    recording = root / 'recording'
    recording.mkdir()
    (root / 'runtime').mkdir(mode=0o700)
    shutil.copyfile(__file__, recording / 'driver.py')
    shutil.copyfile(harness, recording / 'harness.vala')
    build = dict(production_revision=args.revision, binary_sha256=digest(binary),
                 harness_sha256=digest(harness), driver_sha256=digest(Path(__file__)),
                 fixture_sha256=manifest['sha256'], timeout=args.timeout,
                 settle_milliseconds=5000, renderer='cairo',
                 observation_mode=True, command=[str(binary)])
    (recording / 'build.json').write_text(json.dumps(build, indent=2) + '\n')
    environment = dict(os.environ, XDG_DATA_HOME=str(root / 'data'),
                       XDG_CONFIG_HOME=str(root / 'config'), XDG_CACHE_HOME=str(root / 'cache'),
                       XDG_RUNTIME_DIR=str(root / 'runtime'), GSETTINGS_SCHEMA_DIR=str(schemas),
                       GSETTINGS_BACKEND='keyfile', GTK_A11Y='none', NO_AT_BRIDGE='1',
                       GSK_RENDERER='cairo')
    # Baselines must log diagnostics rather than abort at previously known issues.
    environment.pop('G_DEBUG', None)
    started = time.monotonic()
    with (recording / 'application.log').open('w') as log:
        process = subprocess.Popen(['heaptrack', '--output', str(recording / 'heaptrack-transitions'),
                                    str(binary)], env=environment, stdout=log,
                                   stderr=subprocess.STDOUT, start_new_session=True)
        try:
            code = process.wait(timeout=args.timeout)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGTERM)
            try:
                process.wait(timeout=30)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGKILL)
                process.wait()
            (recording / 'driver-result.json').write_text(json.dumps(dict(
                success=False, timeout=True, elapsed_seconds=time.monotonic()-started), indent=2)+'\n')
            raise
    (recording / 'driver-result.json').write_text(json.dumps(dict(
        success=False, exit_code=code, elapsed_seconds=time.monotonic()-started), indent=2) + '\n')
    events = [json.loads(line) for line in (recording / 'events.jsonl').read_text().splitlines()]
    assert code == 0 and events[-1]['event'] == 'success', code
    assert [e['cycle'] for e in events if e['event'] == 'rapid_cycle_end'] == [1, 2, 3, 4]
    assert sum(e['event'] == 'layout_control' for e in events) == 32
    assert sum(e['event'] == 'layout_ready' for e in events) == 8
    assert sum(e['event'] == 'calendar_edge' for e in events) == 60
    assert [e['cycle'] for e in events if e['event'] == 'calendar_date'] == [50, -50, 100, -100, 0]
    assert next(e for e in events if e['event'] == 'sidebar_end')['value'] == 8
    assert sum(e['event'] == 'release_sample' for e in events) == 21
    with sqlite3.connect(root / database) as db:
        assert db.execute('PRAGMA integrity_check').fetchall() == [('ok',)]
        assert not db.execute('PRAGMA foreign_key_check').fetchall()
        assert db.execute('SELECT count(*) FROM Items').fetchone()[0] == manifest['counts']['items']
    result = dict(success=True, exit_code=code, elapsed_seconds=time.monotonic()-started,
                  retained_observations=sum(e['value'] for e in events if e['event'] == 'release_sample'),
                  calendar_max_months=max(e['value'] for e in events if e['event'] in ['calendar_edge', 'calendar_date']))
    (recording / 'driver-result.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result), flush=True)


if __name__ == '__main__':
    main()
